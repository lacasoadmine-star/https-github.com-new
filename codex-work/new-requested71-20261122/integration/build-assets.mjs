import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {publicCatalogue} from './catalogue.mjs';

const root=new URL('./',import.meta.url);
const registry=JSON.parse(await readFile(new URL('../registry.json',root),'utf8'));
const catalogue=publicCatalogue(registry);
const [clientSource,stylesheetSource]=await Promise.all(['new-section.mjs','new-section.css'].map(path=>readFile(new URL(path,root),'utf8')));
const assetRevision=createHash('sha256').update(clientSource).update('\0').update(stylesheetSource).digest('hex').slice(0,24);
const config={catalogue,clientSource,stylesheetSource,assetRevision};
const outputs={
  'worker-assets.mjs':'// Generated by build-assets.mjs from the reviewed requested71 registry.\nexport default '+JSON.stringify(config)+';\n',
  'public-catalogue.json':JSON.stringify(catalogue,null,2)+'\n'
};
const check=process.argv.slice(2).includes('--check');
for(const [name,content] of Object.entries(outputs)){
  const target=new URL(name,root);
  if(check){
    const existing=await readFile(target,'utf8').catch(()=>null);
    if(existing!==content)throw Error('NEW71_GENERATED_FILE_OUTDATED:'+name);
  }else await writeFile(target,content);
}
console.log(JSON.stringify({mode:check?'check':'build',releaseId:catalogue.releaseId,requested:catalogue.requestedCount,ready:catalogue.readyCount,assetRevision,output:fileURLToPath(new URL('worker-assets.mjs',root))}));
