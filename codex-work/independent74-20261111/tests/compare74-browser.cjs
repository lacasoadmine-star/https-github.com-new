const {createServer}=require('node:http');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {chromium}=require('/opt/codex/cua_node/lib/node_modules/playwright');
const root=path.resolve(__dirname,'..');
(async()=>{
 const {createGateway}=await import(path.join(root,'gateway.mjs'));
 const assets=Object.fromEntries(fs.readdirSync(path.join(root,'client')).filter(n=>/\.(html|mjs|css)$/.test(n)).map(n=>['/'+n,{body:fs.readFileSync(path.join(root,'client',n),'utf8'),type:n.endsWith('.html')?'text/html':n.endsWith('.css')?'text/css':'application/javascript',etag:'"compare-test-'+n+'"'}]));
 let accountCalls=0;
 const legacyPaths=[];
 const route=createGateway({assets,previous:{fetch(request){const path=new URL(request.url).pathname;legacyPaths.push(path);if(/^\/(api|v1)\//.test(path))accountCalls++;return new Response('Not found',{status:404});}}});
 const server=createServer(async(req,res)=>{try{const r=await route(new Request('http://127.0.0.1:'+server.address().port+req.url),{},{});res.writeHead(r.status,Object.fromEntries(r.headers));res.end(Buffer.from(await r.arrayBuffer()));}catch(e){res.writeHead(500);res.end(e.message);}});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const origin=process.env.IND74_TEST_REMOTE_ORIGIN||'http://127.0.0.1:'+server.address().port;
 const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1600,height:1000},reducedMotion:'reduce'});
 const ownErrors=[],requests=[];
 page.on('pageerror',e=>{if(e.stack?.includes(origin))ownErrors.push(e.message);});
 page.on('request',r=>{const u=new URL(r.url());if(u.origin===origin&&/\/(api|v1)\//.test(u.pathname))requests.push(u.pathname);});
 const artifact=path.join(root,'tests/artifacts'),tag=process.env.IND74_TEST_REMOTE_ORIGIN?'-production':'';
 try{
  await page.goto(origin+'/independent74/compare74.html',{waitUntil:'domcontentloaded'});
  await page.locator('.card').nth(73).waitFor();assert.equal(await page.locator('.card').count(),74);
  assert.equal(await page.locator('#selection option').count(),74);
  assert.equal(await page.locator('.card small').filter({hasText:'la ilaaliyey'}).count(),2);
  await page.screenshot({path:path.join(artifact,'official74-gallery'+tag+'.png')});
  await page.locator('.card').filter({hasText:'Multi Hot 100'}).click();
  const build=page.frameLocator('#build-frame');
  await build.locator('#title').waitFor();assert.equal(await build.locator('#title').textContent(),'Multi Hot 100');
  await build.locator('#sound-no').click();await build.locator('#turbo').check();
  assert.equal(await build.locator('.reel-column').count(),5);assert.equal(await build.locator('.symbol').count(),20);
  const before=await build.locator('#balance').textContent();
  await build.locator('#bet').fill('2');await build.locator('#play').click();
  await build.locator('#play').waitFor({state:'visible'});await build.locator('#play').isEnabled();
  await page.waitForTimeout(15000);
  const after=await build.locator('#balance').textContent();
  const frames=page.frames().map(f=>f.url()).filter(u=>u.startsWith('https://')&&!u.startsWith(origin)).map(u=>new URL(u).origin+new URL(u).pathname);
  assert(frames.some(u=>u.includes('ssgportal.com')),'The official reference must be opened beside the build.');
  await page.screenshot({path:path.join(artifact,'official74-multihot100-side-by-side'+tag+'.png')});
  assert.equal(ownErrors.length,0,ownErrors.join('; '));assert.equal(accountCalls,0);assert.equal(requests.length,0);
  await page.selectOption('#selection','ind74_official_multihot5');
  assert(await page.locator('#protected').isVisible());assert(await page.locator('#build-frame').isHidden());
  assert.equal(await page.locator('#build-link').getAttribute('href'),'/');
  await page.locator('#gallery-toggle').click();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Mobile gallery overflows.');
  const report={at:new Date().toISOString(),origin,entries:74,protected:2,officialFrames:frames,newBuildTestStake:'2 test points',before,after,ownErrors,accountRequests:requests,legacyPaths,realWalletUsed:false,providerRoundPlayedInThisCheck:false,fullOfficialParityVerified:false};
  fs.writeFileSync(path.join(artifact,'official74-comparison'+tag+'.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
 }finally{await page.close();await browser.close();await new Promise(r=>server.close(r));}
})().catch(e=>{console.error(e);process.exitCode=1;});
