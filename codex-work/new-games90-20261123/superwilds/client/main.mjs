import {SuperWildsRenderer} from '../render/renderer.mjs';
import {superWildsLayout} from '../render/layout.mjs';
import {PAYLINES,PAY_RATIOS,OBSERVED_BETS_MINOR} from '../rules.mjs';
import {SuperWildsController,AUTO_COUNTS,formatMoney,rendererReceipt} from './controller.mjs';
import {SuperWildsAudio} from './audio.mjs';

const labels={menu:'Menu',sound:'Sound',quick:'Quick spin',bet:'Choose bet',auto:'Autoplay',double:'X2 gamble',spin:'HOLD & SPIN',take:'Choose bet'};
let ordinal=0;
const parseLimit=value=>{
  if(!/^(0|[1-9]\d{0,10})(\.\d{1,2})?$/.test(value))throw Error('SUPERWILDS_AUTO_AMOUNT');
  const [whole,decimal='']=value.split('.'),n=Number(whole)*100+Number(decimal.padEnd(2,'0'));
  if(!Number.isSafeInteger(n)||n<=0)throw Error('SUPERWILDS_AUTO_AMOUNT');return n;
};

/** Same-site game mount. Authenticated host injection is required for every round.
 * No round, money balance or RNG is generated by this UI.
 */
export function mountSuperWilds({root,transport=null,subject=null,journalStorage,keyFactory,audioFactory,onExit=null,onError=()=>{}}={}){
  const d=root?.ownerDocument,w=d?.defaultView;
  if(!d||!w)throw TypeError('SUPERWILDS_ROOT_REQUIRED');
  if(root.dataset.superWildsMounted==='true')throw Error('SUPERWILDS_ALREADY_MOUNTED');
  root.dataset.superWildsMounted='true';root.classList.add('sw-root');root.tabIndex=0;
  const id=`sw-${++ordinal}`,listeners=[],buttons=new Map(),held=new Set();
  let disposed=false,frame,modal=null,origin=null,ready=false,layout,clickId=0,count=100,autoNext=false,betOffset=0;
  const settings={effects:true,music:true,fullscreen:false,quick:false};
  const on=(target,type,fn,options)=>{target.addEventListener(type,fn,options);listeners.push(()=>target.removeEventListener(type,fn,options));};
  const stage=d.createElement('div');stage.className='sw-stage';
  const canvas=d.createElement('canvas');canvas.className='sw-scene';canvas.setAttribute('aria-label','Multi Hot 5 Super Wilds reels and multiplier');
  const layer=d.createElement('div');layer.className='sw-controls';
  const status=d.createElement('p');status.className='sw-status';status.setAttribute('role','status');
  const recover=d.createElement('button');recover.type='button';recover.className='sw-recover';recover.textContent='Recover current round';recover.hidden=true;
  const overlay=d.createElement('div');overlay.className='sw-overlay';
  const panel=d.createElement('section');panel.className='sw-panel';panel.setAttribute('role','dialog');panel.setAttribute('aria-modal','true');panel.tabIndex=-1;
  overlay.append(panel);stage.append(canvas,layer,overlay);root.replaceChildren(stage,status,recover);
  const audio=new SuperWildsAudio(audioFactory?{audioFactory}:{});
  const renderer=new SuperWildsRenderer({canvas,onEvent:event=>audio.handle(event),now:()=>w.performance.now()});
  let controller=null;
  if(transport&&subject)controller=new SuperWildsController({transport,subject,journalStorage:journalStorage??w.sessionStorage,
    ...(keyFactory?{keyFactory}:{}),renderer,now:()=>w.performance.now(),onChange:()=>sync(),onError});
  const element=(tag,text,className)=>{const node=d.createElement(tag);if(text!==undefined)node.textContent=text;if(className)node.className=className;return node;};
  const button=(text,action,value)=>{const b=element('button',text);b.type='button';b.dataset.action=action;if(value!==undefined)b.dataset.value=String(value);return b;};
  const snapshot=()=>controller?.snapshot()??{phase:'DISCONNECTED',connected:false,canPlay:false,canDouble:false,betMinor:null,balanceMinor:null,round:null,pending:null,betLevels:[],auto:null,history:[]};
  function resize(){
    if(disposed)return;
    const width=Math.max(240,root.clientWidth||w.innerWidth),height=Math.max(320,w.visualViewport?.height||w.innerHeight);
    layout=superWildsLayout(width,height);stage.style.width=`${width}px`;stage.style.height=`${height}px`;
    renderer.resize(width,height,Math.min(2,w.devicePixelRatio||1));
    for(const[name,node]of buttons){const r=layout.controls[name];Object.assign(node.style,{left:`${r.x}px`,top:`${r.y}px`,width:`${r.width}px`,height:`${r.height}px`});}
    positionPanel();
  }
  for(const[name,label]of Object.entries(labels)){
    const node=button('',name);node.className=`sw-control sw-${name}`;node.setAttribute('aria-label',label);
    node.append(element('span',label,'sw-control-label'));buttons.set(name,node);layer.append(node);
  }
  function header(title,{close=true,exit=false}={}){
    panel.replaceChildren();const h=element('header'),name=element('h2',title);name.id=`${id}-title`;
    if(exit){const leave=button('↤ Exit','exit');leave.className='sw-exit';h.append(leave);}h.append(name);
    if(close)h.append(button('×','close'));panel.append(h);panel.setAttribute('aria-labelledby',name.id);
    const body=element('div',undefined,'sw-panel-content');panel.append(body);return body;
  }
  function positionPanel(){
    if(!layout||modal!=='bet'){panel.style.removeProperty('left');panel.style.removeProperty('top');return;}
    const width=Math.min(365,layout.width-20),height=Math.min(380,layout.height-20);
    const top=layout.portrait?(layout.height-height)/2:layout.scene.y+layout.scene.height*.10;
    panel.style.left=`${Math.max(10,layout.width-width-10)}px`;
    panel.style.top=`${Math.max(10,Math.min(layout.height-height-10,top))}px`;
  }
  function renderBetPicker(){
    const s=snapshot(),maximum=Math.max(0,s.betLevels.length-5);betOffset=Math.max(0,Math.min(maximum,betOffset));
    panel.replaceChildren();panel.removeAttribute('aria-labelledby');panel.setAttribute('aria-label','CHOOSE BET');panel.dataset.betOffset=String(betOffset);
    const rows=element('div',undefined,'sw-bet-rows');rows.setAttribute('aria-label','Bet values');
    for(const value of s.betLevels.slice(betOffset,betOffset+5)){
      const row=button(`${formatMoney(value)} ETB`,'choose-bet',value);row.className='sw-bet-row';
      row.setAttribute('aria-pressed',String(value===s.betMinor));rows.append(row);
    }
    const up=button('⌃','bet-up'),down=button('⌄','bet-down');up.className='sw-bet-up';down.className='sw-bet-down';
    up.setAttribute('aria-label','Previous bet values');down.setAttribute('aria-label','Next bet values');up.disabled=betOffset===0;down.disabled=betOffset===maximum;
    panel.append(rows,up,down);positionPanel();
  }
  function close(){if(!ready)return;overlay.hidden=true;modal=null;layer.inert=false;
    if(origin?.isConnected)origin.focus();else root.focus();origin=null;sync();}
  function show(name,source){
    if(disposed)return;
    if(!overlay.hidden&&modal!==name&&modal==='startup')return;
    const s=snapshot();if(['bet','auto','gamble'].includes(name)&&!['READY','WIN_PENDING'].includes(s.phase))return;
    if(name==='bet'&&(s.phase!=='READY'||s.auto?.active))return;
    if(overlay.hidden)origin=source??d.activeElement;
    modal=name;overlay.hidden=false;layer.inert=true;overlay.dataset.modal=name;panel.dataset.view=name;
    panel.className=`sw-panel ${['rules','settings','history'].includes(name)?'sw-menu-panel':name==='quick'?'sw-quick-panel':name==='bet'?'sw-bet-panel':''}`;
    panel.removeAttribute('aria-label');
    if(name==='startup'){
      const body=header('MULTI HOT 5 SUPER WILDS',{close:false});body.classList.add('sw-startup');body.append(element('p','Would you like to enable sound?'),button('Yes','sound-yes'),button('No','sound-no'));
    }else if(name==='bet'){
      renderBetPicker();
    }else if(name==='quick'){
      const body=header('QUICK PLAY');body.append(button('ENABLE QUICK PLAY','quick-enable'),button('NO','close'));
    }else if(name==='auto'){
      count=100;
      const body=header('AUTOPLAY'),counts=element('div',undefined,'sw-auto-counts');
      for(const value of AUTO_COUNTS){const b=button(String(value),'auto-count',value);b.setAttribute('aria-pressed',String(value===count));counts.append(b);}body.append(counts,element('h3','STOP AUTOPLAY'));
      const limits=element('div',undefined,'sw-limits');
      for(const[key,label]of [['winLimit','If a win reaches or exceeds'],['decreaseLimit','If balance decreases'],['increaseLimit','If balance increases']]){
        const row=element('label'),toggle=d.createElement('input'),value=d.createElement('input');toggle.type='checkbox';toggle.dataset.limitToggle=key;toggle.setAttribute('aria-label',`Enable ${label.toLowerCase()}`);
        value.type='text';value.inputMode='decimal';value.dataset.limitValue=key;value.disabled=true;value.setAttribute('aria-label',`${label} ETB`);value.placeholder='ETB';
        row.append(toggle,element('span',label),value);limits.append(row);
      }
      const start=button('START PLAY','auto-start');start.className='sw-start';start.disabled=!s.canPlay;body.append(limits,start);
    }else if(name==='gamble'){
      const body=header('X2 — GAMBLE');body.append(element('p',`WIN ${formatMoney(s.round?.winMinor??0)} ETB`));
      const red=button('RED','guess','RED'),black=button('BLACK','guess','BLACK');red.disabled=black.disabled=!s.canDouble;body.append(red,black,button('TAKE WIN','take'));
      if(!s.canDouble)body.append(element('p','The server has not enabled X2 for this game.'));
    }else{
      const body=header(name==='rules'?'RULES & PAYTABLE':name==='history'?'HISTORY':'SETTINGS',{exit:true});
      if(name==='settings'){
        body.classList.add('sw-settings-content');
        for(const[key,label]of [['effects','Sound Effects'],['music','Background Music'],['fullscreen','Full Screen']]){
          const row=element('label',label),input=d.createElement('input');input.type='checkbox';input.checked=settings[key];input.dataset.setting=key;row.append(input);body.append(row);
        }
      }else if(name==='history'){
        if(!s.history.length)body.append(element('p','No rounds recorded in this session.'));
        else{const table=element('table'),tr=element('tr');for(const text of ['Round','Action','Bet','Win'])tr.append(element('th',text));table.append(tr);
          for(const h of s.history){const row=element('tr');for(const value of [h.roundId.slice(-8),h.action,formatMoney(h.betMinor),formatMoney(h.winMinor)])row.append(element('td',value));table.append(row);}body.append(table);}
      }else{
        const rulesBet=s.betMinor??OBSERVED_BETS_MINOR[0];
        body.append(element('p',`All symbol wins shown for total BET ${formatMoney(rulesBet)} ETB.`));
        const table=element('table'),head=element('tr');for(const label of ['Symbol','3','4','5'])head.append(element('th',label));table.append(head);
        for(const[symbol,pays]of Object.entries(PAY_RATIOS)){const row=element('tr');row.append(element('th',symbol.toUpperCase()));for(const count of [3,4,5]){
          const numerator=BigInt(rulesBet)*BigInt(pays[count]);row.append(element('td',numerator%2n===0n?formatMoney(Number(numerator/2n)):'Fractional minor unit'));}table.append(row);}body.append(table);
        body.append(element('p','Winning symbols connect from the leftmost reel. WILD can replace another symbol. The highest combination on each of the five fixed lines pays. The accepted server multiplier applies to the line win.'));
        const paths=element('div',undefined,'sw-paylines');for(const[index,rows]of PAYLINES.entries()){
          const svg=d.createElementNS('http://www.w3.org/2000/svg','svg');svg.setAttribute('viewBox','0 0 120 70');svg.setAttribute('role','img');svg.setAttribute('aria-label',`Payline ${index+1}`);
          const path=d.createElementNS('http://www.w3.org/2000/svg','polyline');path.setAttribute('points',rows.map((r,c)=>`${10+c*25},${10+r*25}`).join(' '));path.setAttribute('stroke','#ffdb39');path.setAttribute('stroke-width','3');path.setAttribute('fill','none');svg.append(path);paths.append(svg);}body.append(paths);
        body.append(element('p','TAKE WIN collects an accepted win. The next SPIN can collect the previous win before its new stake. STOP speeds presentation only. Autoplay stops when its count or selected limits are reached and turns off after a disconnection.'));
      }
      const nav=element('nav');nav.setAttribute('role','tablist');nav.setAttribute('aria-label','Game menu');
      for(const[title,action]of [['Rules','rules'],['Settings','settings'],['History','history']]){
        const b=button(title,action);b.setAttribute('role','tab');b.setAttribute('aria-selected',String(name===action));b.tabIndex=name===action?0:-1;nav.append(b);
      }panel.append(nav);
    }
    positionPanel();panel.focus();sync();
  }
  function sync(){
    if(disposed)return;const s=snapshot(),moving=['WAITING','ANIMATING'].includes(s.phase),win=s.phase==='WIN_PENDING';
    renderer.setDisplay({balanceMinor:s.balanceMinor,betMinor:s.betMinor,winMinor:s.round?.winMinor??0,currency:'ETB',quick:settings.quick,
      auto:s.auto?.active??false,muted:!settings.effects,winPending:win,doubleEnabled:win&&s.canDouble});
    buttons.get('spin').setAttribute('aria-label',moving?'STOP':'HOLD & SPIN');buttons.get('take').setAttribute('aria-label',win?'TAKE WIN':'Choose bet');
    for(const[name,b]of buttons){
      b.disabled=!ready||(name==='spin'&&(!s.canPlay||!s.connected||['RECOVERY','TAKING','DOUBLE_PENDING','DISCONNECTED'].includes(s.phase)))||
        (name==='double'&&(!win||!s.canDouble))||(name==='bet'&&(s.phase!=='READY'||s.auto?.active||!s.betLevels.length))||
        (name==='take'&&(!['READY','WIN_PENDING'].includes(s.phase)||!s.connected))||
        (['menu','quick'].includes(name)&&!['READY','WIN_PENDING','DISCONNECTED'].includes(s.phase))||
        (name==='auto'&&(!s.canPlay||!s.connected||!['READY','WIN_PENDING'].includes(s.phase)&&!s.auto?.active));
      b.setAttribute('aria-pressed',String(name==='quick'?settings.quick:name==='sound'?settings.effects:name==='auto'?!!s.auto?.active:false));
    }
    buttons.get('double').hidden=!win;recover.hidden=s.phase!=='RECOVERY'||!s.pending;recover.disabled=controller?.busy!=null;
    status.textContent=s.phase==='RECOVERY'?'Connection interrupted. Recover the current round.':!transport?'Player connection unavailable.':!s.connected?'Connecting to player session…':!s.canPlay?'Game connection is not enabled by the server.':s.auto?.active?`AUTO ${s.auto.remaining}`:'';
    root.dataset.phase=s.phase;root.dataset.cashEnabled=String(s.canPlay&&s.connected);root.dataset.modal=modal??'';root.dataset.quick=String(settings.quick);
  }
  async function action(name,value,source){
    if(disposed)return;audio.once('button',`click-${++clickId}`);
    try{
      if(name==='sound-yes'||name==='sound-no'){
        settings.effects=settings.music=name==='sound-yes';audio.setting(settings);if(settings.effects)await audio.unlock();ready=true;close();
      }else if(name==='close')close();
      else if(name==='exit'){controller?.stopAuto('EXIT');suspend('EXIT');if(typeof onExit==='function')await onExit();else w.location.assign('/');}
      else if(name==='menu'||name==='rules')show('rules',source);
      else if(['settings','history','bet'].includes(name))show(name,source);
      else if(name==='quick'){if(settings.quick){settings.quick=false;if(controller)controller.quick=false;sync();}else show('quick',source);}
      else if(name==='quick-enable'){settings.quick=true;if(controller)controller.quick=true;close();}
      else if(name==='sound'){settings.effects=settings.music=!settings.effects;audio.setting(settings);if(settings.effects)await audio.unlock();sync();}
      else if(name==='choose-bet'){controller?.selectBet(Number(value));close();}
      else if(name==='bet-up'||name==='bet-down'){
        betOffset+=name==='bet-up'?-5:5;renderBetPicker();
        (panel.querySelector(`[data-action=${name}]:not(:disabled)`)??panel.querySelector('[data-action=choose-bet]'))?.focus();
      }
      else if(name==='auto'){if(snapshot().auto?.active)controller.stopAuto();else show('auto',source);}
      else if(name==='auto-count'){count=Number(value);for(const b of panel.querySelectorAll('[data-action=auto-count]'))b.setAttribute('aria-pressed',String(Number(b.dataset.value)===count));}
      else if(name==='auto-start'){
        const limits={};for(const key of ['winLimit','decreaseLimit','increaseLimit']){const active=panel.querySelector(`[data-limit-toggle=${key}]`).checked;limits[key]=active?parseLimit(panel.querySelector(`[data-limit-value=${key}]`).value):null;}
        controller?.configureAuto({count,...limits});close();controller?.startAuto();
      }else if(name==='spin'){controller.quick=settings.quick;await controller?.spin();}
      else if(name==='take'){if(snapshot().phase==='WIN_PENDING'){close();await controller?.take();}else show('bet',source);}
      else if(name==='double')show('gamble',source);
      else if(name==='guess'){close();await controller?.double(value);}
      sync();
    }catch(error){onError(error);status.textContent='That action is currently unavailable. Check the entered values.';}
  }
  on(stage,'click',event=>{const target=event.target.closest?.('button[data-action]');if(target&&!target.disabled&&stage.contains(target))void action(target.dataset.action,target.dataset.value,target);});
  on(overlay,'click',event=>{if(event.target===overlay&&modal==='bet')close();});
  on(recover,'click',()=>{void controller?.recover();});
  on(panel,'change',event=>{const target=event.target;
    if(target.dataset.limitToggle){panel.querySelector(`[data-limit-value=${target.dataset.limitToggle}]`).disabled=!target.checked;return;}
    const key=target.dataset.setting;if(!key)return;
    if(key==='fullscreen'){
      const task=target.checked?root.requestFullscreen?.():d.exitFullscreen?.();Promise.resolve(task).catch(onError);return;
    }
    settings[key]=target.checked;if(key==='effects'){settings.music=target.checked;const m=panel.querySelector('[data-setting=music]');if(m)m.checked=settings.music;}
    audio.setting(settings);if(settings.effects)void audio.unlock();sync();
  });
  on(d,'fullscreenchange',()=>{settings.fullscreen=d.fullscreenElement===root;const box=panel.querySelector('[data-setting=fullscreen]');if(box)box.checked=settings.fullscreen;resize();});
  on(root,'keydown',event=>{
    if(event.key==='Escape'&&!overlay.hidden){event.preventDefault();close();return;}
    if(event.target.getAttribute?.('role')==='tab'&&['ArrowLeft','ArrowRight','Home','End'].includes(event.key)){
      event.preventDefault();const tabs=['rules','settings','history'],current=tabs.indexOf(modal);
      const index=event.key==='Home'?0:event.key==='End'?2:(current+(event.key==='ArrowRight'?1:2))%3;
      show(tabs[index]);panel.querySelector(`[role=tab][data-action=${tabs[index]}]`).focus();return;
    }
    if(event.key==='Tab'&&!overlay.hidden){const nodes=[...panel.querySelectorAll('button:not(:disabled),input:not(:disabled),select')].filter(n=>!n.hidden&&n.tabIndex>=0&&n.getClientRects().length>0);
      if(!nodes.length){event.preventDefault();return;}const first=nodes[0],last=nodes.at(-1);
      if(event.shiftKey&&(d.activeElement===first||d.activeElement===panel)){event.preventDefault();last.focus();}
      else if(!event.shiftKey&&(d.activeElement===last||d.activeElement===panel)){event.preventDefault();first.focus();}return;
    }
    if(![' ','Enter'].includes(event.key))return;
    if(event.repeat||held.has(event.key)){event.preventDefault();return;}held.add(event.key);
    if(!overlay.hidden||event.target.closest?.('button,input,select,textarea'))return;
    event.preventDefault();if(ready&&!buttons.get('spin').disabled)void action('spin');
  });
  on(root,'keyup',event=>held.delete(event.key));on(w,'blur',()=>{held.clear();controller?.stopAuto('BLUR');});
  const suspend=reason=>{held.clear();controller?.stopAuto(reason);void audio.suspend();};
  on(d,'visibilitychange',()=>{if(d.hidden)suspend('HIDDEN');});on(w,'offline',()=>{suspend('OFFLINE');controller?.disconnect();});
  on(w,'pagehide',()=>{suspend('PAGEHIDE');controller?.disconnect();});
  on(w,'online',()=>{void controller?.connect().catch(onError);});
  on(w,'pageshow',event=>{if(event.persisted)void controller?.connect().catch(onError);});
  on(w,'resize',resize);if(w.visualViewport)on(w.visualViewport,'resize',resize);
  function tick(now){
    if(disposed)return;renderer.tick(now);renderer.draw();const view=renderer.snapshot(),s=snapshot();
    if(s.phase==='ANIMATING'&&['IDLE','READY','SETTLED'].includes(view.phase))controller.finishPresentation(s.round.roundId);
    const next=snapshot();if(ready&&overlay.hidden&&next.auto?.active&&!autoNext&&['READY','WIN_PENDING'].includes(next.phase)&&!controller.busy){
      autoNext=true;Promise.resolve(controller.spin({auto:true})).finally(()=>{autoNext=false;});
    }
    frame=w.requestAnimationFrame(tick);
  }
  resize();show('startup');frame=w.requestAnimationFrame(tick);
  const connected=controller?controller.connect().then(result=>{const round=snapshot().round;if(round)renderer.acceptReceipt(rendererReceipt(round),w.performance.now());sync();return result;})
    .catch(error=>{onError(error);status.textContent='Player connection unavailable.';return false;}):Promise.resolve(false);
  return Object.freeze({controller,renderer,audio,connected,settings:()=>({...settings}),snapshot:()=>snapshot(),
    dispose(){if(disposed)return;suspend('DISPOSED');controller?.dispose();renderer.dispose();audio.dispose();disposed=true;w.cancelAnimationFrame(frame);for(const remove of listeners)remove();delete root.dataset.superWildsMounted;root.replaceChildren();}});
}
