import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {join,dirname} from 'node:path';
import {PREFIX,RELEASE} from './native-catalog.mjs';
const root=dirname(fileURLToPath(import.meta.url)),worker=join(root,'../worker'),assets=[],imports=[],modules=[];
const sha=body=>createHash('sha256').update(body).digest('hex');
await mkdir(join(worker,'native-catalog-data'),{recursive:true});
for(const name of ['portal.mjs','native-catalog.mjs','native-catalog.css','foxy-hot-20.webp','multi-hot-5.webp']){
 const bytes=await readFile(join(root,name)),type=name.endsWith('.webp')?'image/webp':name.endsWith('.css')?'text/css; charset=utf-8':'application/javascript; charset=utf-8';
 const moduleName='native-catalog-data/'+name+'.bin',variable='asset'+assets.length;
 await writeFile(join(worker,moduleName),bytes);
 imports.push('import '+variable+' from '+JSON.stringify('./'+moduleName)+';');
 assets.push({name,variable,type,bytes:bytes.length,sha256:sha(bytes)});
 modules.push({name:moduleName,type:'application/octet-stream',bytes:bytes.length,sha256:sha(bytes)});
}
const body='// Generated by native-portal/build.mjs. Typed Data modules retain exact public bytes.\n'+imports.join('\n')+'\nexport const assets={'+assets.map(asset=>JSON.stringify(asset.name)+':{body:'+asset.variable+',type:'+JSON.stringify(asset.type)+',etag:'+JSON.stringify('"'+asset.sha256+'"')+',size:'+asset.bytes+'}').join(',')+'};\n';
await writeFile(join(worker,'native-catalog-assets.mjs'),body);
for(const name of ['native-catalog.mjs','native-catalog-assets.mjs']){const bytes=await readFile(join(worker,name));modules.push({name,type:'application/javascript+module',bytes:bytes.length,sha256:sha(bytes)});}
const publicResources=assets.map(asset=>({path:PREFIX+asset.name,type:asset.type,bytes:asset.bytes,sha256:asset.sha256}));
const manifest={release:RELEASE,prefix:PREFIX,entryExport:'installNativeCatalog(previous, assets)',assetsExport:'assets',modules,publicResources};
await writeFile(join(worker,'native-catalog-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify(manifest,null,2));
