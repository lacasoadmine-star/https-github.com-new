import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('./',import.meta.url),base='/native-library/balloon/v1/';
const files={};
for(const name of ['index.html','balloon.css','balloon.js','cover.svg','lobby.mjs','catalog.mjs'])files[name]=await readFile(new URL(name,root),'utf8');
files['index.html']=files['index.html'].replace('href="./balloon.css"','href="'+base+'balloon.css"').replace('src="./balloon.js"','src="'+base+'balloon.js"');
const output='// Generated by prepare-assets.mjs; no image/video overlays.\nexport const ASSETS='+JSON.stringify(files)+';\n';
await writeFile(new URL('client-assets.mjs',root),output);
console.log(JSON.stringify({files:Object.fromEntries(Object.entries(files).map(([k,v])=>[k,v.length])),bundleBytes:Buffer.byteLength(output)}));
