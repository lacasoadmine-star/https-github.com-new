test('a changed file after an earlier copy discards the entire staged package', async t => {
  const base = await temporary(t), items = [{value: 1}, {value: 2}].map(value => {const bytes = jsonBytes(value); return {bytes, entry: locked(bytes)};}).sort((a, b) => a.entry.file.localeCompare(b.entry.file));
  const inventory = buildInventory([sourceGroup('smartsoft', [{id: 'alpha_native', assets: items.map(item => item.entry)}])]);
  const cacheRoots = await caches(base, {smartsoft: items});
  await writeFile(join(cacheRoots.smartsoft, items[1].entry.file), Buffer.alloc(items[1].entry.bytes, 0));
  const outputDir = join(base, 'package');
  await assert.rejects(copyStaticAssets(inventory, {cacheRoots, outputDir}), errorCode('ASSET_CHANGED'));
  assert.equal(await exists(outputDir), false);
  assert.deepEqual(await readdir(base), ['smartsoft']);
  assert.deepEqual(await readFile(join(cacheRoots.smartsoft, items[0].entry.file)), items[0].bytes);
});

test('successful assembly verifies every route, deduplicates content and never links to source cache bytes', async t => {
  const base = await temporary(t), bytes = jsonBytes({bones: [{name: 'root'}]}), entry = locked(bytes);
  const inventory = buildInventory([sourceGroup('smartsoft', [{id: 'alpha_native', assets: [entry]}]), sourceGroup('arcade', [{id: 'beta_native', assets: [entry]}])]);
  const cacheRoots = await caches(base, {smartsoft: [{bytes, entry}], arcade: [{bytes, entry}]});
  const outputDir = join(base, 'package'), receipt = await copyStaticAssets(inventory, {cacheRoots, outputDir});
  assert.equal(receipt.binaryVerified, true);
  assert.equal(receipt.verifiedFiles, 2);
  assert.equal(receipt.copiedContents, 1);
  assert.equal(receipt.hardlinkedPaths, 1);
  assert.equal(receipt.writtenAssetBytes, bytes.length);
  assert.equal(receipt.networkRequests, 0);
  assert.equal(receipt.deploymentPerformed, false);
  assert.equal(receipt.replacesExistingAssetManifest, false);
  assert.equal(receipt.mergeStrategy, 'additive-preserve-existing');
  const paths = Object.keys(inventory.files).map(path => join(receipt.staticDirectory, path.slice(1)));
  for (const path of paths) assert.deepEqual(await readFile(path), bytes);
  assert.equal((await lstat(paths[0])).ino, (await lstat(paths[1])).ino);
  assert.notEqual((await lstat(paths[0])).ino, (await lstat(join(cacheRoots.smartsoft, entry.file))).ino);
  await writeFile(join(cacheRoots.smartsoft, entry.file), Buffer.alloc(bytes.length));
  assert.deepEqual(await readFile(paths[0]), bytes);
  const inventoryBytes = await readFile(receipt.inventoryPath);
  assert.equal(sha256(inventoryBytes), receipt.inventorySha256);
  assert.deepEqual(JSON.parse(inventoryBytes), inventory);
  assert.deepEqual(JSON.parse(await readFile(join(outputDir, 'build-receipt.json'), 'utf8')), receipt);
});

