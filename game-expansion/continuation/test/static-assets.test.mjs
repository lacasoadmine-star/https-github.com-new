test('reference-art metadata cannot turn on production, money actions or executable resources', () => {
  const bytes = jsonBytes({bones: []});
  for (const extra of [{productionLaunchEnabled: true}, {financialActions: true}, {capabilities: {financialActions: true}}]) {
    assert.throws(() => buildInventory([sourceGroup('smartsoft', [{id: 'alpha_native', extra}])]), errorCode('UNSAFE_PRESENTATION_MANIFEST'));
  }
  for (const extension of ['js', 'mjs', 'cjs', 'html', 'wasm', 'exe', 'py']) {
    assert.throws(() => buildInventory([sourceGroup('smartsoft', [{id: 'alpha_native', assets: [locked(bytes, extension)]}])]), errorCode('UNSUPPORTED_ASSET_TYPE'));
  }
  for (const sourceURL of ['https://static.example/runtime.js', 'https://static.example/runtime.%6as']) {
    assert.throws(() => buildInventory([sourceGroup('smartsoft', [{id: 'alpha_native', assets: [locked(bytes, 'json', {sourceURL})]}])]), errorCode('EXECUTABLE_SOURCE'));
  }
  assert.throws(() => buildInventory([sourceGroup('smartsoft', [{id: 'alpha_native', assets: [locked(bytes, 'json', {sourceURL: 'https://user:password@static.example/file.json'})]}])]), errorCode('INVALID_SOURCE_URL'));
});

test('readInventory pins the actual source bytes and rejects traversal or symbolic metadata files', async t => {
  const root = join(await temporary(t), 'presentation');
  const group = sourceGroup('smartsoft', [{id: 'alpha_native', assets: [locked(jsonBytes({frames: []}))]}]);
  await writePresentation(root, [group]);
  const inventory = await readInventory({presentationRoot: root});
  const path = join(root, group.games[0].manifestFile);
  const bytes = await readFile(path);
  assert.deepEqual(inventory.sourceDocuments[group.games[0].manifestFile], {sha256: sha256(bytes), bytes: bytes.length});
  const indexPath = join(root, GROUP_INDEXES.smartsoft);
  await writeFile(indexPath, jsonBytes({schemaVersion: 1, productionLaunchEnabled: false, games: {alpha_native: {file: '../escape.json'}}}));
  await assert.rejects(readInventory({presentationRoot: root}), errorCode('INVALID_SOURCE_PATH'));
  await writePresentation(root, [group]);
  const original = join(root, 'original.json');
  await writeFile(original, bytes); await rm(path); await symlink(original, path);
  await assert.rejects(readInventory({presentationRoot: root}), errorCode('INVALID_SOURCE_FILE'));
});

test('every allowed static type has an explicit MIME type and a matching signature', () => {
  const samples = {
    png: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==', 'base64'),
    jpg: Buffer.from([255, 216, 255, 224]), gif: Buffer.from('GIF89a'),
    webp: Buffer.from('RIFF0000WEBP'), mp3: Buffer.from('ID3\u0003\u0000\u0000'),
    woff: Buffer.from('wOFF0000'), woff2: Buffer.from('wOF20000'),
    ttf: Buffer.from([0, 1, 0, 0]), otf: Buffer.from('OTTO0000'),
    json: jsonBytes({skeleton: {spine: '4.1'}, bones: [{name: 'root'}]}),
    txt: Buffer.from('page.png\nsize: 16,16\nregion\n  bounds: 0,0,8,8\n'),
    atlas: Buffer.from('page.png\nsize: 16,16\nregion\n  bounds: 0,0,8,8\n'),
    svg: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"><defs><linearGradient id="g"/></defs><path fill="url(#g)" d="M0 0L1 1"/></svg>'),
  };
  assert.deepEqual(Object.keys(samples).sort(), Object.keys(MIME_TYPES).sort());
  for (const [extension, bytes] of Object.entries(samples)) {
    const entry = locked(bytes, extension);
    assert.equal(verifyStaticBytes(entry.file, entry, bytes), true);
  }
});

test('matching a hash alone never permits executable or externally loading SVG/data content', () => {
  const bad = [
    ['png', '<html>bad image</html>', 'MIME_MISMATCH'],
    ['json', '<html>bad data</html>', 'EXECUTABLE_CONTENT'],
    ['json', '{"type":"Script","data":"doSomething()"}', 'EXECUTABLE_CONTENT'],
    ['json', '{"frames":', 'INVALID_STATIC_DATA'],
    ['txt', 'const injected = true;', 'EXECUTABLE_CONTENT'],
    ['svg', '<svg><script>alert(1)</script></svg>', 'EXECUTABLE_CONTENT'],
    ['svg', '<svg onload="alert(1)"></svg>', 'EXECUTABLE_CONTENT'],
    ['svg', '<svg><image href="https://example.com/image.png"/></svg>', 'EXECUTABLE_CONTENT'],
    ['svg', '<svg><style>@import "https://example.com/style.css";</style></svg>', 'EXECUTABLE_CONTENT'],
    ['svg', '<?xml-stylesheet href="https://example.com/style.css"?><svg/>', 'EXECUTABLE_CONTENT'],
    ['svg', '<svg><foreignObject><html/></foreignObject></svg>', 'EXECUTABLE_CONTENT'],
  ];
  for (const [extension, text, code] of bad) {
    const bytes = Buffer.from(text), entry = locked(bytes, extension);
    assert.throws(() => verifyStaticBytes(entry.file, entry, bytes), errorCode(code), text);
  }
  const bytes = Buffer.from([255, 254, 253]), entry = locked(bytes, 'txt');
  assert.throws(() => verifyStaticBytes(entry.file, entry, bytes), errorCode('INVALID_STATIC_DATA'));
});

test('a changed hash or byte count is rejected independently of allowed file signatures', () => {
  const bytes = jsonBytes({value: 10}), changed = jsonBytes({value: 20}), entry = locked(bytes);
  assert.equal(bytes.length, changed.length);
  assert.throws(() => verifyStaticBytes(entry.file, entry, changed), errorCode('ASSET_CHANGED'));
  assert.throws(() => verifyStaticBytes(entry.file, entry, Buffer.concat([bytes, Buffer.from(' ')])), errorCode('ASSET_CHANGED'));
});

