  assert.throws(() => buildInventory([group, sourceGroup('arcade', [{id: 'alpha_native', assets: [asset]}])]), errorCode('INVALID_MANIFEST'));
  assert.throws(() => buildInventory([{...group, indexFile: '../index.json'}]), errorCode('INVALID_SOURCE_PATH'));
  assert.throws(() => buildInventory([{...group, indexFile: 'arcade/index.json'}]), errorCode('INVALID_INDEX_PATH'));
